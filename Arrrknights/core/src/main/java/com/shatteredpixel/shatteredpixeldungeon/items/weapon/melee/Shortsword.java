public class Shortsword extends MeleeWeapon {

	public static final float ABILITY_PARALYSIS = 1f;

	{
		image = ItemSpriteSheet.SHORTSWORD;
		hitSound = Assets.Sounds.HIT_DUALSTRIKE;
		hitSoundPitch = 1.1f;

		tier = 2;
	}

	@Override
	public String targetingPrompt() {
		return Messages.get(this, "prompt");
	}

	@Override
	protected void duelistAbility(Hero hero, Integer target) {
		//+(3+lvl) damage on top of a regular hit, roughly +20% base damage
		int dmgBoost = augment.damageFactor(3 + buffedLvl());
		sheathStrike(hero, target, 1f, dmgBoost);
	}

	@Override
	public String abilityInfo() {
		int dmgBoost = levelKnown ? 3 + buffedLvl() : 3;
		if (levelKnown){
			return Messages.get(this, "ability_desc", augment.damageFactor(min()+dmgBoost), augment.damageFactor(max()+dmgBoost));
		} else {
			return Messages.get(this, "typical_ability_desc", min(0)+dmgBoost, max(0)+dmgBoost);
		}
	}

	//a quick strike out of the sheath: hits a nearby enemy and paralyses it briefly
	private void sheathStrike(Hero hero, Integer target, float dmgMulti, int dmgBoost) {
		if (target == null) {
			return;
		}

		final Char enemy = Actor.findChar(target);
		if (enemy == null || enemy == hero || hero.isCharmedBy(enemy) || !Dungeon.level.heroFOV[target]) {
			GLog.w(Messages.get(this, "ability_no_target"));
			return;
		}

		hero.belongings.abilityWeapon = this;
		if (!hero.canAttack(enemy)) {
			GLog.w(Messages.get(this, "ability_target_range"));
			hero.belongings.abilityWeapon = null;
			return;
		}
		hero.belongings.abilityWeapon = null;

		hero.sprite.attack(enemy.pos, new Callback() {
			@Override
			public void call() {
				beforeAbilityUsed(hero, enemy);
				AttackIndicator.target(enemy);

				if (hero.attack(enemy, dmgMulti, dmgBoost, Char.INFINITE_ACCURACY)) {
					Sample.INSTANCE.play(Assets.Sounds.HIT_STRONG);
					if (enemy.isAlive()) {
						Buff.affect(enemy, Paralysis.class, ABILITY_PARALYSIS);
					} else {
						MeleeWeapon.onAbilityKill(hero, enemy);
					}
				}

				Invisibility.dispel();
				hero.spendAndNext(hero.attackDelay());
				afterAbilityUsed(hero);
			}
		});
	}
}
